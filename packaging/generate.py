#!/usr/bin/env python3
"""Generate the Homebrew formula and winget manifests for a release.

    packaging/generate.py v0.1.0 path/to/SHA256SUMS

Writes Formula/near-drive.rb (this repo doubles as a Homebrew tap) and
packaging/winget/manifests/i/ilblackdragon/NEARDrive/<version>/*.yaml (ready
to submit to microsoft/winget-pkgs). The release workflow runs this after
publishing; it only needs the release's SHA256SUMS.
"""
import pathlib
import sys

REPO = "ilblackdragon/near-drive"
ROOT = pathlib.Path(__file__).resolve().parent.parent
BINS = ["near-drive", "near-drive-gateway", "near-drive-tray"]
DESCRIPTION = "End-to-end encrypted storage addressed by NEAR accounts: CLI, synced folders, files on demand, S3 endpoint"
# Homebrew: at most 80 characters, no leading article.
FORMULA_DESC = "End-to-end encrypted storage for NEAR accounts, with folder sync"
WINGET_ID = "ilblackdragon.NEARDrive"
WINGET_SCHEMA = "1.6.0"


def sums(path):
    out = {}
    for line in pathlib.Path(path).read_text().splitlines():
        if line.strip():
            digest, name = line.split(maxsplit=1)
            out[name.lstrip("*")] = digest
    return out


def url(tag, asset):
    return f"https://github.com/{REPO}/releases/download/{tag}/{asset}"


def formula(tag, s):
    version = tag.lstrip("v")
    mac = "near-drive-universal-apple-darwin.tar.gz"
    lx = "near-drive-x86_64-unknown-linux-gnu.tar.gz"
    la = "near-drive-aarch64-unknown-linux-gnu.tar.gz"
    return f'''# Generated by packaging/generate.py for {tag}; do not edit by hand.
class NearDrive < Formula
  desc "{FORMULA_DESC}"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    url "{url(tag, mac)}"
    sha256 "{s[mac]}"
  end

  on_linux do
    on_intel do
      url "{url(tag, lx)}"
      sha256 "{s[lx]}"
    end
    on_arm do
      url "{url(tag, la)}"
      sha256 "{s[la]}"
    end
  end

  def install
    bin.install {", ".join(f'"{b}"' for b in BINS)}
  end

  def caveats
    <<~EOS
      NEAR Drive uses near-cli-rs for your NEAR keys:
        curl --proto '=https' --tlsv1.2 -LsSf https://github.com/near/near-cli-rs/releases/latest/download/near-cli-rs-installer.sh | sh
      Then: near drive login
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/near-drive --version")
    assert_match version.to_s, shell_output("#{{bin}}/near-drive-gateway --version")
  end
end
'''


def winget(tag, s):
    version = tag.lstrip("v")
    zip_ = "near-drive-x86_64-pc-windows-msvc.zip"
    header = lambda kind: (
        f"# Generated by packaging/generate.py for {tag}.\n"
        f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.{WINGET_SCHEMA}.schema.json\n"
    )
    nested = "\n".join(
        f"      - RelativeFilePath: near-drive-x86_64-pc-windows-msvc\\{b}.exe\n        PortableCommandAlias: {b}" for b in BINS
    )
    return {
        f"{WINGET_ID}.yaml": header("version")
        + f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\nDefaultLocale: en-US\nManifestType: version\nManifestVersion: {WINGET_SCHEMA}\n",
        f"{WINGET_ID}.installer.yaml": header("installer")
        + f"""PackageIdentifier: {WINGET_ID}
PackageVersion: {version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
{nested}
Installers:
  - Architecture: x64
    InstallerUrl: {url(tag, zip_)}
    InstallerSha256: {s[zip_].upper()}
ManifestType: installer
ManifestVersion: {WINGET_SCHEMA}
""",
        f"{WINGET_ID}.locale.en-US.yaml": header("defaultLocale")
        + f"""PackageIdentifier: {WINGET_ID}
PackageVersion: {version}
PackageLocale: en-US
Publisher: NEAR Drive contributors
PublisherUrl: https://github.com/{REPO}
PackageName: NEAR Drive
PackageUrl: https://github.com/{REPO}
License: MIT OR Apache-2.0
LicenseUrl: https://github.com/{REPO}/blob/{tag}/LICENSE-MIT
ShortDescription: "{DESCRIPTION}"
Moniker: near-drive
Tags:
  - near
  - storage
  - encryption
  - sync
  - cli
ReleaseNotesUrl: https://github.com/{REPO}/releases/tag/{tag}
ManifestType: defaultLocale
ManifestVersion: {WINGET_SCHEMA}
""",
    }


def main():
    tag, sums_path = sys.argv[1], sys.argv[2]
    s = sums(sums_path)
    (ROOT / "Formula").mkdir(exist_ok=True)
    (ROOT / "Formula" / "near-drive.rb").write_text(formula(tag, s))
    d = ROOT / "packaging" / "winget" / "manifests" / "i" / "ilblackdragon" / "NEARDrive" / tag.lstrip("v")
    d.mkdir(parents=True, exist_ok=True)
    for name, text in winget(tag, s).items():
        (d / name).write_text(text)
    print(f"wrote Formula/near-drive.rb and {d.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
